"""Generate the firmware's protocol header and golden test vectors from src/aapi/protocol/."""

from enum import IntEnum
from pathlib import Path

from aapi.protocol import framing, ids
from aapi.protocol.ids import Address
from aapi.protocol.messages import HEADER_LEN, Packet, Resume, Stop, Text
from aapi.protocol.serial_msgs import LoraRx

ROOT = Path(__file__).resolve().parent.parent
IDS_H = ROOT / "firmware/lib/aapi_proto/aapi_ids.h"
GOLDEN_H = ROOT / "firmware/test/golden_vectors.h"

# Negative rssi and snr check sign handling; the packet looks like a LoRa header + payload.
GOLDEN_LORA_RX = LoraRx(
    rssi_dbm=-137, snr_qdb=-50, packet=bytes.fromhex("a502000aff00")
)

# Test-only network ID; the real one comes from config (sent down in CONFIG).
GOLDEN_NET_ID = 0xA5


def golden_packets() -> list[tuple[str, Packet]]:
    """Real LoRa packets for the C++ header parser and classify() tests."""
    net, base, rover = GOLDEN_NET_ID, Address.BASE, 3
    return [
        ("stop_rover3", Stop(net, src=base, dst=rover, seq=7, reason=1)),
        ("stop_all", Stop(net, src=base, dst=Address.BROADCAST, seq=8, reason=2)),
        ("resume_rover3", Resume(net, src=base, dst=rover, seq=9)),
        ("text_from_rover3", Text(net, src=rover, dst=base, seq=200, text=b"hi")),
    ]


BANNER = "// GENERATED by tools/gen_ids.py from src/aapi/protocol/.\n"


# Each enum in ids.py -> its C++ namespace.
ID_GROUPS: list[tuple[type[IntEnum], str, str]] = [
    (
        ids.SerialType,
        "serial",
        "Serial frame types, byte 0 of a frame (ids.SerialType)",
    ),
    (ids.LoraType, "lora", "LoRa packet types, byte 1 of the header (ids.LoraType)"),
    (ids.Address, "addr", "LoRa src/dst addresses (ids.Address)"),
]


def full_block_payload(msg_type: int) -> bytes:
    """Payload whose body (type + payload + CRC) is exactly 254 zero-free bytes.

    COBS then ends on a full block with no trailing count byte. The last payload byte is
    chosen so that neither CRC byte is zero.
    """
    head = bytes(i % 255 + 1 for i in range(250))
    for last in range(1, 256):
        payload = head + bytes([last])
        crc = framing.crc16(bytes([msg_type]) + payload)
        if crc & 0xFF and crc >> 8:
            return payload
    raise AssertionError("no zero-free CRC found")  # can't happen: 255 tries


def golden_inputs() -> list[tuple[int, bytes]]:
    """Fixed (type, payload) inputs covering the COBS edge cases."""
    long_len = min(260, framing.MAX_PAYLOAD_LEN)  # crosses a 254-byte COBS block
    inputs: list[tuple[int, bytes]] = [
        (ids.SerialType.HEARTBEAT, b""),
        (
            ids.SerialType.DRIVE,
            bytes.fromhex("000500ff00"),
        ),  # zeros inside and at both ends
        (
            ids.SerialType.LORA_TX,
            bytes(i % 255 + 1 for i in range(long_len)),
        ),  # no zeros
        (
            ids.SerialType.LORA_RX,
            bytes(i % 7 for i in range(framing.MAX_PAYLOAD_LEN)),
        ),  # max size
    ]
    if framing.MAX_PAYLOAD_LEN >= 251:  # body ends exactly on a full COBS block
        inputs.append(
            (ids.SerialType.LORA_TX, full_block_payload(ids.SerialType.LORA_TX))
        )
    return inputs


def c_bytes(data: bytes) -> str:
    if not data:
        return "{0x00}"  # C++ has no zero-length arrays; the length field says 0
    rows = [
        ", ".join(f"0x{b:02X}" for b in data[i : i + 12])
        for i in range(0, len(data), 12)
    ]
    return "{\n    " + ",\n    ".join(rows) + ",\n}"


def render_ids() -> str:
    lines = [
        BANNER,
        "#pragma once\n",
        "#include <stddef.h>",
        "#include <stdint.h>\n",
        "namespace aapi {",
    ]
    for enum, namespace, comment in ID_GROUPS:
        lines += [f"// {comment}", f"namespace {namespace} {{"]
        lines += [f"constexpr uint8_t {m.name} = 0x{m.value:02X};" for m in enum]
        lines.append(f"}}  // namespace {namespace}\n")
    lines += [
        "// Frame limits (framing.py)",
        f"constexpr size_t CRC_LEN = {framing.CRC_len};",
        f"constexpr size_t MAX_LORA_PACKET = {framing.MAX_LORA_PACKET};",
        f"constexpr size_t LORA_RX_HEADER_LEN = {framing.LORA_RX_HEADER_LEN};",
        f"constexpr size_t LORA_HEADER_LEN = {HEADER_LEN};  // messages.HEADER_LEN",
        f"constexpr size_t MAX_PAYLOAD_LEN = {framing.MAX_PAYLOAD_LEN};",
        f"constexpr size_t MAX_BODY_LEN = {framing.MAX_BODY_LEN};",
        "// COBS-encoded body, without the 0x00 end marker",
        f"constexpr size_t MAX_ENCODED_LEN = {framing.MAX_ENCODED_LEN};",
        "}  // namespace aapi",
    ]
    return "\n".join(lines) + "\n"


def render_golden() -> str:
    lines = [
        BANNER,
        "// Frames built by framing.encode_frame()",
        "#pragma once\n",
        "#include <stddef.h>",
        "#include <stdint.h>\n",
        "struct GoldenVector {",
        "  uint8_t type;",
        "  const uint8_t* payload;",
        "  size_t payload_len;",
        "  const uint8_t* frame;  // includes the 0x00 end marker",
        "  size_t frame_len;",
        "};\n",
    ]
    entries = []
    for i, (msg_type, payload) in enumerate(golden_inputs()):
        frame = framing.encode_frame(msg_type, payload)
        lines.append(f"static const uint8_t GV{i}_PAYLOAD[] = {c_bytes(payload)};")
        lines.append(f"static const uint8_t GV{i}_FRAME[] = {c_bytes(frame)};\n")
        entries.append(
            f"    {{0x{msg_type:02X}, GV{i}_PAYLOAD, {len(payload)}, "
            f"GV{i}_FRAME, {len(frame)}}},"
        )
    lines += ["static const GoldenVector GOLDEN_VECTORS[] = {", *entries, "};"]
    lines.append(
        "static const size_t GOLDEN_COUNT = sizeof(GOLDEN_VECTORS) / sizeof(GOLDEN_VECTORS[0]);"
    )

    rx = GOLDEN_LORA_RX
    lines += [
        "\n// LORA_RX payload built by serial_msgs.LoraRx.encode()",
        f"static const int16_t GOLDEN_LORA_RX_RSSI = {rx.rssi_dbm};",
        f"static const int8_t GOLDEN_LORA_RX_SNR_QDB = {rx.snr_qdb};",
        f"static const uint8_t GOLDEN_LORA_RX_PACKET[] = {c_bytes(rx.packet)};",
        f"static const size_t GOLDEN_LORA_RX_PACKET_LEN = {len(rx.packet)};",
        f"static const uint8_t GOLDEN_LORA_RX_PAYLOAD[] = {c_bytes(rx.encode())};",
        f"static const size_t GOLDEN_LORA_RX_PAYLOAD_LEN = {len(rx.encode())};",
    ]

    lines += [
        "\n// LoRa packets built by messages.py; the header fields are what parse_header must return",
        "struct GoldenPacket {",
        "  const char* label;",
        "  const uint8_t* bytes;",
        "  size_t len;",
        "  uint8_t net_id, type, src, dst, seq;",
        "};\n",
        f"static const uint8_t GOLDEN_NET_ID = 0x{GOLDEN_NET_ID:02X};",
    ]
    entries = []
    for label, pkt in golden_packets():
        data, h = pkt.encode(), pkt.header()
        lines.append(f"static const uint8_t GP_{label.upper()}[] = {c_bytes(data)};")
        entries.append(
            f'    {{"{label}", GP_{label.upper()}, {len(data)}, 0x{h.net_id:02X}, '
            f"0x{h.type:02X}, 0x{h.src:02X}, 0x{h.dst:02X}, 0x{h.seq:02X}}},"
        )
    lines += ["static const GoldenPacket GOLDEN_PACKETS[] = {", *entries, "};"]
    lines.append(
        "static const size_t GOLDEN_PACKET_COUNT = sizeof(GOLDEN_PACKETS) / sizeof(GOLDEN_PACKETS[0]);"
    )
    return "\n".join(lines) + "\n"


def render() -> dict[Path, str]:
    return {IDS_H: render_ids(), GOLDEN_H: render_golden()}


def main() -> None:
    for path, text in render().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
